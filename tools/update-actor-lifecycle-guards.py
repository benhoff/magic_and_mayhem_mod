#!/usr/bin/env python3
"""Reproduce complete No-CD body guards for the actor lifecycle adapter."""
import hashlib
from pathlib import Path
import struct
import subprocess

ROOT=Path(__file__).resolve().parents[1]
PIN='40209ca76705b5db04ea1974543bdec1739c68acdebdbefe2537ed025b8b7168'
RANGES=[(0x505db0,0x505f70),(0x505f70,0x50607c),(0x5060a0,0x50621c),
        (0x5065e0,0x506d25),(0x506290,0x5065d7),(0x51f5e0,0x51fa5c),
        (0x506d30,0x5070a8),(0x473100,0x4731ff),(0x4bfef0,0x4c0077),
        (0x4c00d0,0x4c0191),(0x52a5c0,0x52a632),(0x52a640,0x52a661),(0x52baf0,0x52bc30)]

def main():
    subprocess.run([ROOT/'tools/original-manifest.sh','verify'],check=True)
    try:
        raw=(ROOT/'original/Arcane_Nocd/Chaos.exe').read_bytes()
        if hashlib.sha256(raw).hexdigest()!=PIN:raise ValueError('Unsupported original build')
        pe=struct.unpack_from('<I',raw,60)[0];section=pe+24+struct.unpack_from('<H',raw,pe+20)[0]
        sections=[struct.unpack_from('<4I',raw,section+40*i+8) for i in range(struct.unpack_from('<H',raw,pe+6)[0])]
        def body(start,end):
            for _,rva,size,offset in sections:
                at=start-0x400000-rva
                if 0<=at<=size-(end-start):return raw[offset+at:offset+at+end-start]
            raise ValueError('Body is not file-backed')
        lines=['#pragma once','/* Generated by tools/update-actor-lifecycle-guards.py; full pinned bodies. */']
        for i,(start,end) in enumerate(RANGES):
            lines.append(f'static const unsigned char actor_bytes_{i}[]={{')
            data=body(start,end)
            lines.extend(','.join('0x'+format(b,'02x') for b in data[n:n+16])+',' for n in range(0,len(data),16))
            lines.append('};')
        lines+=['struct ActorOriginal {unsigned address,size;const unsigned char* bytes;};','static const ActorOriginal mnm_actor_original[]={']
        lines.extend(f'{{0x{start:x},{end-start},actor_bytes_{i}}},' for i,(start,end) in enumerate(RANGES))
        lines.append('};')
        (ROOT/'runtime/actor-lifecycle/original_bytes.h').write_text('\n'.join(lines)+'\n')
    finally:subprocess.run([ROOT/'tools/original-manifest.sh','verify'],check=True)

if __name__=='__main__':main()
