#!/usr/bin/env python3
"""Reproduce the complete No-CD world cell producer and adjacent switch guards."""
from pathlib import Path
import subprocess
from original_x86 import PE32

ROOT=Path(__file__).resolve().parents[1]
PIN='40209ca76705b5db04ea1974543bdec1739c68acdebdbefe2537ed025b8b7168'

def main():
    subprocess.run([ROOT/'tools/original-manifest.sh','verify'],check=True)
    try:
        pe=PE32((ROOT/'original/Arcane_Nocd/Chaos.exe').read_bytes())
        if pe.sha256!=PIN:raise ValueError('Unsupported original build')
        # Function body ends at4fbcb1; its adjacent dispatch tables/padding end
        # at the next recorded function4fbe00. Guard data without patching it.
        data=pe.read(0x4f8960,0x4fbe00-0x4f8960)
        lines=['#pragma once','/* Generated by tools/update-world-cell-producer-guards.py. */',
            'static const unsigned char mnm_world_cell_original[]={']
        lines.extend(','.join('0x'+format(v,'02x') for v in data[n:n+16])+',' for n in range(0,len(data),16))
        lines.append('};')
        (ROOT/'runtime/world-cell-producer/original_bytes.h').write_text('\n'.join(lines)+'\n')
    finally:subprocess.run([ROOT/'tools/original-manifest.sh','verify'],check=True)

if __name__=='__main__':main()
