#!/usr/bin/env python3
"""Export pinned immutable effect view tables/constants into owned native source."""
import argparse,hashlib,json,struct,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
PIN='40209ca76705b5db04ea1974543bdec1739c68acdebdbefe2537ed025b8b7168'
def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--executable',type=Path,required=True);p.add_argument('--header',type=Path,required=True);p.add_argument('--record',type=Path,required=True);a=p.parse_args()
 if a.header.exists() or a.record.exists():raise ValueError('Export paths must be new')
 subprocess.run([ROOT/'tools/original-manifest.sh','verify'],check=True)
 try:
  data=a.executable.read_bytes();assert hashlib.sha256(data).hexdigest()==PIN
  pe=struct.unpack_from('<I',data,60)[0];optional=pe+24;assert struct.unpack_from('<I',data,optional+28)[0]==0x400000
  count=struct.unpack_from('<H',data,pe+6)[0];start=optional+struct.unpack_from('<H',data,pe+20)[0];sections=[struct.unpack_from('<IIII',data,start+i*40+8) for i in range(count)]
  def at(address,size):
   rva=address-0x400000
   for virtual,rva_start,raw_size,raw in sections:
    if rva>=rva_start and rva-rva_start+size<=raw_size:return data[raw+rva-rva_start:raw+rva-rva_start+size]
   raise ValueError('Address lacks backed section storage')
  result=dict(schema=1,original_sha256=PIN,tables={},constants={},raw={})
  lines=['// Generated by tools/export-effect-view-tables.py from the pinned NoCD build.','#pragma once','#include <array>','#include <cstdint>','namespace mnm::reconstruction {']
  for name,address,n in [('EffectType20Views',0x5dfb38,36),('EffectType63Views',0x5dfd78,4)]:
   raw=at(address,n*4*4);values=struct.unpack('<'+'i'*(n*4),raw);views=[list(values[v*n:(v+1)*n]) for v in range(4)];result['tables'][name]=views;result['raw'][hex(address)]=raw.hex();lines.append(f'inline constexpr std::array<std::array<std::int32_t,{n}>,4> {name}{{{{')
   lines += [' {{'+','.join(str(v) for v in row)+'}},' for row in views];lines.append('}};')
  for name,address,fmt in [('EffectAngleZero',0x5c5380,'d'),('EffectAngleHalf',0x5c5a88,'d'),('EffectAnglePi',0x5c6250,'f'),('EffectAngle16Scale',0x5c6260,'f'),('EffectAngle8Scale',0x5c7138,'f'),('EffectAngle8Turn',0x5c713c,'f')]:
   raw=at(address,struct.calcsize(fmt));value=struct.unpack('<'+fmt,raw)[0];result['constants'][name]=value;result['raw'][hex(address)]=raw.hex();lines.append(f'inline constexpr long double {name}={value.hex()}L;')
  lines.append('}');a.header.write_text('\n'.join(lines)+'\n');result['header_sha256']=hashlib.sha256(a.header.read_bytes()).hexdigest();result['success']=True
 finally:
  subprocess.run([ROOT/'tools/original-manifest.sh','verify'],check=True)
 result['original_manifest_verified_before_after']=True;a.record.write_text(json.dumps(result,indent=2)+'\n');print(json.dumps(dict(success=True,constants=result['constants'],header=str(a.header))))
if __name__=='__main__':main()
